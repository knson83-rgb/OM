alter table public.final_orders
drop constraint if exists final_orders_ingredient_type_check;

alter table public.final_orders
add constraint final_orders_ingredient_type_check check (ingredient_type in ('main', 'seasoning'));

alter table public.final_orders
drop constraint if exists final_orders_status_check;

alter table public.final_orders
add constraint final_orders_status_check check (status in ('ordered', 'received', 'cancelled'));

create index if not exists final_orders_ordered_at_idx
on public.final_orders (ordered_at desc, id desc);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  event_type text not null,
  entity_type text not null default '',
  entity_id text not null default '',
  action text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_logs_created_at_idx
on public.audit_logs (created_at desc, id desc);

create index if not exists audit_logs_entity_idx
on public.audit_logs (entity_type, entity_id, created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists draft_orders_touch_updated_at on public.draft_orders;
create trigger draft_orders_touch_updated_at
before update on public.draft_orders
for each row execute function public.touch_updated_at();

drop trigger if exists final_orders_touch_updated_at on public.final_orders;
create trigger final_orders_touch_updated_at
before update on public.final_orders
for each row execute function public.touch_updated_at();

