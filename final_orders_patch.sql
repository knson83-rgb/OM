create index if not exists final_orders_ordered_at_idx
on public.final_orders (ordered_at desc, id desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists final_orders_touch_updated_at on public.final_orders;
create trigger final_orders_touch_updated_at
before update on public.final_orders
for each row execute function public.touch_updated_at();

alter table public.final_orders enable row level security;

