alter table public.draft_orders
add column if not exists order_amount numeric not null default 0;

update public.draft_orders
set order_amount = qty * unit_price
where order_amount = 0
  and unit_price > 0;

alter table public.draft_orders
drop constraint if exists draft_orders_order_amount_check;

alter table public.draft_orders
add constraint draft_orders_order_amount_check check (order_amount >= 0);

create table if not exists public.final_orders (
  id bigint generated by default as identity primary key,
  order_no text not null,
  item_name text not null,
  qty numeric not null check (qty >= 0),
  unit text not null,
  order_amount numeric not null default 0 check (order_amount >= 0),
  status text not null default 'ordered'
    check (status in ('ordered', 'received', 'cancelled')),
  memo text not null default '',
  ordered_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

